"""Pydantic schemas for the ASRA HTTP API.

Mirrors the TypeScript contracts defined in Frontend/lib/types.ts so that
the frontend and backend remain strictly synchronized.
"""

from __future__ import annotations

from typing import Any, List, Literal, Optional
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Supported comparison species IDs (matching Ensembl genus_species format)
# ---------------------------------------------------------------------------
SpeciesId = Literal[
    "mus_musculus",
    "rattus_norvegicus",
    "macaca_mulatta",
    "macaca_fascicularis",
    "canis_lupus_familiaris",
    "sus_scrofa",
    "oryctolagus_cuniculus",
    "cavia_porcellus",
    "danio_rerio",
]

# The four biological evidence layers
LayerName = Literal[
    "sequence",
    "localisation",
    "cell_expression",
    "tissue_expression",
]

# Status of a layer execution
LayerStatus = Literal["ok", "incomplete", "unavailable"]

# Qualitative concern levels for agent findings (no numeric scores)
Concern = Literal["high", "moderate", "low", "flagged"]


# ---------------------------------------------------------------------------
# Request schema
# ---------------------------------------------------------------------------

class AssessmentRequest(BaseModel):
    """Payload sent by the frontend submission form."""

    species: SpeciesId = Field(
        ...,
        description="Target comparison species in Ensembl notation.",
    )
    sequence: str = Field(
        ...,
        description="Normalised amino acid sequence (uppercase, no whitespace).",
    )
    sequenceLabel: Optional[str] = Field(
        None,
        description="User-supplied label or FASTA header (e.g. gene name).",
    )


# ---------------------------------------------------------------------------
# Evidence Layer schemas
# ---------------------------------------------------------------------------

class SourceRecord(BaseModel):
    """Citation record pointing to an external scientific database."""

    id: str = Field(..., description="Stable database accession or record ID.")
    source: str = Field(..., description="Origin database, e.g. UniProt, Ensembl.")
    url: Optional[str] = Field(None, description="Optional direct link to the record.")


class Observation(BaseModel):
    """A single factual measurement within an evidence layer."""

    field: str = Field(..., description="Metric or attribute name.")
    value: str = Field(..., description="Observed quantitative or categorical value.")
    sourceRecordId: Optional[str] = Field(
        None,
        description="ID of the SourceRecord providing this observation.",
    )


class LayerResult(BaseModel):
    """Standard contract returned for each of the four evidence layers."""

    gene: Optional[str] = Field(None, description="Identified gene symbol if resolved.")
    species: SpeciesId = Field(..., description="Comparison species ID.")
    layer: LayerName = Field(..., description="Name of the evidence layer.")
    status: LayerStatus = Field(..., description="Execution status of this layer.")
    observations: List[Observation] = Field(
        default_factory=list,
        description="List of observations measured for this layer.",
    )
    source_records: List[SourceRecord] = Field(
        default_factory=list,
        description="Traceable citations supporting this layer.",
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Known caveats or limitations in the underlying data.",
    )
    data_version: Optional[str] = Field(
        None,
        description="Version or release number of the data source.",
    )


# ---------------------------------------------------------------------------
# Agent finding & Sequence stats schemas
# ---------------------------------------------------------------------------

class Finding(BaseModel):
    """A scientific claim generated by the multi-agent pipeline."""

    id: str = Field(..., description="Unique UUID for this finding.")
    claim: str = Field(..., description="One-sentence statement of difference.")
    mechanism: str = Field(
        ...,
        description="Interpreter's mechanistic explanation of potential impact.",
    )
    concern: Concern = Field(
        ...,
        description="Qualitative level of translational concern.",
    )
    citedField: str = Field(
        ...,
        description="<layer>.<field> observation backing this claim.",
    )
    sourceRecordId: str = Field(
        ...,
        description="SourceRecord ID validating this finding.",
    )
    scepticNote: Optional[str] = Field(
        None,
        description="Optional commentary or caveat from the Sceptic audit.",
    )


class ResidueFraction(BaseModel):
    """Residue frequency entry for sequence composition."""

    residue: str
    fraction: float


class SequenceStats(BaseModel):
    """Computed physicochemical metrics for the submitted protein sequence."""

    length: int
    estimatedMassKDa: float
    composition: List[ResidueFraction]


# ---------------------------------------------------------------------------
# Full report response schema
# ---------------------------------------------------------------------------

class Report(BaseModel):
    """Complete assessment report consumed by Frontend/components/report/ReportView."""

    id: str = Field(..., description="Unique assessment run UUID.")
    generatedAt: str = Field(..., description="ISO 8601 UTC timestamp.")
    origin: Literal["mock", "live"] = Field(
        "live",
        description="Indicates whether the report was generated by live agents.",
    )
    request: AssessmentRequest
    sequenceStats: SequenceStats
    layers: List[LayerResult]
    findings: List[Finding]
    recommendedExperiments: List[str]
    limitations: List[str]
